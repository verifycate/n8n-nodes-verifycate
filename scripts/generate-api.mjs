#!/usr/bin/env node
// Generates the API contract used by the node from the committed OpenAPI
// snapshot. Labels and help text stay hand-written in the node, but every
// method and path comes from the published document, so a removed or renamed
// route fails the build instead of failing inside a customer workflow.
//
// Usage:
//   node scripts/generate-api.mjs
//   node scripts/generate-api.mjs --check

import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.dirname(fileURLToPath(new URL('../package.json', import.meta.url)));
const specPath = path.join(root, 'openapi', 'openapi.json');
const outPath = path.join(root, 'shared', 'generated', 'api.ts');

// The public operations this package calls. Keep this list in sync with the
// API helpers in shared/transport.ts.
const OPERATIONS = {
	getWorkspace: { method: 'GET', path: '/api/v1/workspaces/current' },

	listCertificates: { method: 'GET', path: '/api/v1/workspaces/{slug}/certificates' },
	createCertificate: { method: 'POST', path: '/api/v1/workspaces/{slug}/certificates' },
	getCertificate: { method: 'GET', path: '/api/v1/workspaces/{slug}/certificates/{id}' },
	updateCertificate: { method: 'PATCH', path: '/api/v1/workspaces/{slug}/certificates/{id}' },
	deleteCertificate: { method: 'DELETE', path: '/api/v1/workspaces/{slug}/certificates/{id}' },

	listIssues: { method: 'GET', path: '/api/v1/workspaces/{slug}/certificates/{id}/issues' },
	importIssues: { method: 'POST', path: '/api/v1/workspaces/{slug}/certificates/{id}/issues' },
	getIssue: { method: 'GET', path: '/api/v1/workspaces/{slug}/issues/{issueID}' },
	updateIssue: { method: 'PATCH', path: '/api/v1/workspaces/{slug}/issues/{issueID}' },
	deleteIssue: { method: 'DELETE', path: '/api/v1/workspaces/{slug}/issues/{issueID}' },
	issueCertificate: { method: 'POST', path: '/api/v1/workspaces/{slug}/issues/{issueID}/issue' },
	reissueCertificate: {
		method: 'POST',
		path: '/api/v1/workspaces/{slug}/issues/{issueID}/reissue',
	},
	remindIssue: { method: 'POST', path: '/api/v1/workspaces/{slug}/issues/{issueID}/remind' },
	revokeIssue: { method: 'POST', path: '/api/v1/workspaces/{slug}/issues/{issueID}/revoke' },
	replaceIssue: { method: 'POST', path: '/api/v1/workspaces/{slug}/issues/{issueID}/replace' },

	listRecipients: { method: 'GET', path: '/api/v1/workspaces/{slug}/recipients' },
	getRecipient: { method: 'GET', path: '/api/v1/workspaces/{slug}/recipients/{email}' },

	listRequests: { method: 'GET', path: '/api/v1/workspaces/{slug}/requests' },
	approveRequest: { method: 'POST', path: '/api/v1/workspaces/{slug}/requests/{id}/approve' },
	rejectRequest: { method: 'POST', path: '/api/v1/workspaces/{slug}/requests/{id}/reject' },
	reopenRequest: { method: 'POST', path: '/api/v1/workspaces/{slug}/requests/{id}/reopen' },

	listCorrections: { method: 'GET', path: '/api/v1/workspaces/{slug}/corrections' },
	approveCorrection: { method: 'POST', path: '/api/v1/workspaces/{slug}/corrections/{id}/approve' },
	rejectCorrection: { method: 'POST', path: '/api/v1/workspaces/{slug}/corrections/{id}/reject' },
	reopenCorrection: { method: 'POST', path: '/api/v1/workspaces/{slug}/corrections/{id}/reopen' },

	listWebhooks: { method: 'GET', path: '/api/v1/workspaces/{slug}/webhooks' },
	createWebhook: { method: 'POST', path: '/api/v1/workspaces/{slug}/webhooks' },
	getWebhook: { method: 'GET', path: '/api/v1/workspaces/{slug}/webhooks/{webhookID}' },
	deleteWebhook: { method: 'DELETE', path: '/api/v1/workspaces/{slug}/webhooks/{webhookID}' },
};

const spec = JSON.parse(await readFile(specPath, 'utf8'));

for (const [name, operation] of Object.entries(OPERATIONS)) {
	const item = spec.paths?.[operation.path];
	if (!item) {
		throw new Error(`${name}: path is not in the public API: ${operation.path}`);
	}
	if (!item[operation.method.toLowerCase()]) {
		throw new Error(`${name}: ${operation.method} is not documented for ${operation.path}`);
	}
}

const header = [
	'// Generated by scripts/generate-api.mjs from openapi/openapi.json.',
	'// Do not edit; run `npm run api:generate` after `npm run spec:sync`.',
	'',
].join('\n');

const body = [
	`export const SPEC = ${JSON.stringify(
		{ title: spec.info?.title ?? 'Verifycate API', version: spec.info?.version ?? null },
		null,
		2,
	)} as const;`,
	'',
	`export const OPERATIONS = ${JSON.stringify(OPERATIONS, null, 2)} as const;`,
	'',
	'export type ApiOperationName = keyof typeof OPERATIONS;',
	'',
].join('\n');

const generated = `${header}\n${body}`;
const check = process.argv.includes('--check');

if (check) {
	let current = '';
	try {
		current = await readFile(outPath, 'utf8');
	} catch {
		current = '';
	}
	if (current !== generated) {
		console.error('shared/generated/api.ts is stale. Run `npm run api:generate`.');
		process.exit(1);
	}
	console.log('shared/generated/api.ts matches openapi/openapi.json.');
} else {
	await mkdir(path.dirname(outPath), { recursive: true });
	await writeFile(outPath, generated);
	console.log(
		`Wrote shared/generated/api.ts (${Object.keys(OPERATIONS).length} operations) ` +
			`from ${spec.info?.title ?? 'Verifycate API'} ${spec.info?.version ?? 'unversioned'}.`,
	);
}
